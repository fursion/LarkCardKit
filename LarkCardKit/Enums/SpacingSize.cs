namespace LarkCardKit.Enums;

/// <summary>
/// 间距尺寸枚举
/// 定义飞书卡片中间距的预设值
/// 用于设置组件之间的间距大小
/// </summary>
public enum SpacingSize
{
    /// <summary>
    /// 小间距
    /// 对应 4px
    /// </summary>
    Small,
    
    /// <summary>
    /// 中间距
    /// 对应 8px
    /// </summary>
    Medium,
    
    /// <summary>
    /// 大间距
    /// 对应 12px
    /// </summary>
    Large,
    
    /// <summary>
    /// 超大间距
    /// 对应 16px
    /// </summary>
    ExtraLarge
}
