namespace LarkCardKit.Enums;

/// <summary>
/// 对齐类型枚举
/// 定义飞书卡片中组件的对齐方式
/// </summary>
public enum AlignType
{
    /// <summary>
    /// 左对齐
    /// 水平方向靠左对齐
    /// </summary>
    Left,
    
    /// <summary>
    /// 居中对齐
    /// 水平或垂直方向居中对齐
    /// </summary>
    Center,
    
    /// <summary>
    /// 右对齐
    /// 水平方向靠右对齐
    /// </summary>
    Right,
    
    /// <summary>
    /// 顶部对齐
    /// 垂直方向靠上对齐
    /// </summary>
    Top,
    
    /// <summary>
    /// 底部对齐
    /// 垂直方向靠下对齐
    /// </summary>
    Bottom
}
